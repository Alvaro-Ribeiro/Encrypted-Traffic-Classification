def simulate_twitch(interface,filename):
	options=Options()
	options.add_argument("--no-sandbox")
	options.add_argument("--disable-blink-features=AutomationControlled")
	options.add_argument("--disable-blink-features")
	service = Service('/usr/bin/chromedriver')
	driver = webdriver.Chrome(service=service, options=options)
	driver.execute_cdp_cmd(
        "Page.addScriptToEvaluateOnNewDocument",
        {
            "source": """
                // remove webdriver flag
                Object.defineProperty(navigator, 'webdriver', {
                  get: () => undefined
                });

                // mascarar plugins vazios
                Object.defineProperty(navigator, 'plugins', {
                  get: () => [1, 2, 3, 4, 5]
                });

                // mascarar languages
                Object.defineProperty(navigator, 'languages', {
                  get: () => ['pt-BR', 'pt', 'en-US']
                });

                // mascarar chrome.runtime indicando extensão fake
                window.chrome = {
                  runtime: {}
                };

                // reduzir chance de detectar Headless
                Object.defineProperty(navigator, 'hardwareConcurrency', {
                  get: () => 8
                });
            """
        }
    )
	try:
		capture_thread = threading.Thread(target=capture_packets, args=(interface,filename), daemon=True)
		link = get_link()
		print(link)
		driver.get(link)
		capture_thread.start()
		driver.find_element(By.ID, 'movie_player').send_keys(Keys.SPACE)
		sleep(90)
		stop_capture_flag.set()
		capture_thread.join()
		stop_capture_flag.clear()
	finally:
		driver.quit()

